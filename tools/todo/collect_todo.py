#!/usr/bin/env python3
"""Write TODO.md: every open milestone in a docs/ README and every @todo in
the code, grouped by the docs folder each belongs to.

An open milestone keeps its sub-goals. An open sub-goal under a finished
milestone keeps that milestone as its heading. A code @todo lands under the
deepest docs folder its path mirrors, so include/, src/, tests/ and
benchmarks/ files sit beside their module's milestones.
"""

import argparse
import re
import sys
from pathlib import Path

_ITEM_RE = re.compile(r"^(\s*)- (\[( |x)\] )?(.*)$")
_TODO_RE = re.compile(r"@todo:?\s*(.*?)\s*(\*/)?\s*$")
_CODE_ROOTS = ("include", "src", "tests", "benchmarks")
_CODE_SUFFIXES = {".hpp", ".cpp", ".h", ".py", ".txt", ".cmake"}
_PLATFORM = "platform"


def _milestone_lines(text: str) -> list[str]:
    out, inside = [], False
    for line in text.splitlines():
        if line.startswith("## "):
            inside = line.strip() == "## Milestones"
            continue
        if inside and line.strip():
            out.append(line)
    return out


def open_milestones(text: str) -> list[str]:
    """Open items with their sub-goals, plus the finished parent of any open
    sub-goal, re-indented to four spaces a level."""
    items = []
    for line in _milestone_lines(text):
        m = _ITEM_RE.match(line)
        if not m:
            continue
        indent, box, mark, body = m.groups()
        items.append((len(indent.expandtabs(4)), box is not None, mark == "x", body))

    keep = [False] * len(items)
    stack: list[int] = []
    for i, (depth, boxed, done, _) in enumerate(items):
        while stack and items[stack[-1]][0] >= depth:
            stack.pop()
        open_ancestor = any(items[j][1] and not items[j][2] for j in stack)
        if (boxed and not done) or (not boxed and open_ancestor):
            keep[i] = True
            for j in stack:
                keep[j] = True
        stack.append(i)

    levels: list[int] = []
    out = []
    for (depth, boxed, done, body), kept in zip(items, keep):
        while levels and levels[-1] >= depth:
            levels.pop()
        levels.append(depth)
        if not kept:
            continue
        box = ("[x] " if done else "[ ] ") if boxed else ""
        out.append(f"{'    ' * (len(levels) - 1)}- {box}{body}")
    return out


def folder_of(readme: Path, docs: Path) -> str:
    rel = readme.parent.relative_to(docs).as_posix()
    return _PLATFORM if rel == "." else rel


def owner(path: Path, folders: set[str]) -> str:
    """Deepest docs folder the path mirrors, else its own directory."""
    parts = path.parent.parts
    if parts and parts[0] in _CODE_ROOTS:
        parts = parts[1:]
    for n in range(len(parts), 0, -1):
        candidate = "/".join(parts[:n])
        if candidate in folders:
            return candidate
    return path.parent.as_posix()


def code_todos(root: Path) -> list[tuple[Path, int, str]]:
    found = []
    for base in (*_CODE_ROOTS, "python", "tools"):
        for path in sorted((root / base).rglob("*")):
            if path.suffix not in _CODE_SUFFIXES or not path.is_file():
                continue
            if path.resolve() == Path(__file__).resolve():
                continue
            text = path.read_text(encoding="utf-8", errors="replace")
            for n, line in enumerate(text.splitlines(), 1):
                m = _TODO_RE.search(line)
                if m:
                    found.append((path.relative_to(root), n, m.group(1)))
    return found


def render(root: Path) -> str:
    docs = root / "docs"
    readmes = sorted(docs.rglob("README.md"))
    folders = {folder_of(r, docs) for r in readmes}

    milestones = {folder_of(r, docs): (r, open_milestones(r.read_text(encoding="utf-8")))
                  for r in readmes}
    todos: dict[str, list[str]] = {}
    for path, line, text in code_todos(root):
        todos.setdefault(owner(path, folders), []).append(
            f"- [`{path.as_posix()}:{line}`]({path.as_posix()}#L{line}) {text}")

    order = sorted(set(milestones) | set(todos), key=lambda f: (f != _PLATFORM, f))
    out = [
        "# TODO",
        "",
        "Open milestones from every `docs/` README and every `@todo` in the code, by folder. "
        "Generated by `tools/todo/collect_todo.py` on commit, so edit those sources, not this file.",
    ]
    for folder in order:
        readme, items = milestones.get(folder, (None, []))
        notes = todos.get(folder, [])
        if not items and not notes:
            continue
        title = f"[{folder}]({readme.relative_to(root).as_posix()})" if readme else folder
        out += ["", f"## {title}"]
        if items:
            out += ["", *items]
        if notes:
            out += ["", "Code:", "", *notes]
    return "\n".join(out) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("root", nargs="?", default=Path(__file__).resolve().parents[2], type=Path)
    parser.add_argument("--check", action="store_true",
                        help="exit 1 when TODO.md is out of date instead of writing it")
    args = parser.parse_args()

    target = args.root / "TODO.md"
    text = render(args.root)
    current = target.read_text(encoding="utf-8") if target.exists() else ""
    if args.check:
        if current != text:
            print("TODO.md is out of date, run tools/todo/collect_todo.py", file=sys.stderr)
            return 1
        return 0
    if current != text:
        target.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
