#!/usr/bin/env python3
"""The sweep's results as one markdown page, a table per workload.

    python3 tools/netbench/to_md.py benchmarks/network/results/results.json --env benchmarks/network/results/env.json \
        -o benchmarks/network/results/RESULTS.md

A variant is a backend and a receive path. Each figure is the median across a variant's valid
repetitions. Latency is the peer's send to the bytes reaching user space.
"""

import argparse
import json
import pathlib
import statistics
from collections import defaultdict

PERCENTILES = ["p50", "p90", "p99", "p99.9", "max"]


def fmt_ns(ns):
    if ns is None:
        return ""
    if ns < 1_000:
        return f"{ns:.0f} ns"
    if ns < 1_000_000:
        return f"{ns / 1_000:.2f} µs"
    return f"{ns / 1_000_000:.2f} ms"


def median(values):
    values = [v for v in values if v is not None]
    return statistics.median(values) if values else None


def stage(run, name, key):
    h = run["receiver"]["stages"][name]
    return h[key] if h["count"] else None


def rate(run):
    elapsed = run["peer"]["elapsed_ns"]
    c = run["receiver"]["counters"]
    return (c["messages"] + c["warmup"]) / elapsed * 1e9 if elapsed else None


def loss(run):
    sent = run["peer"]["count"] + run["peer"]["warmup"]
    return run["receiver"]["counters"]["gaps"] / sent if sent else None


def table(runs):
    by_variant = defaultdict(list)
    for r in runs:
        by_variant[(r["backend"], r["net"])].append(r)
    head = ["Variant", "Valid", *PERCENTILES, "k→u p50", "k→u p99", "msg/s", "lost"]
    lines = ["| " + " | ".join(head) + " |", "|" + " --- |" * len(head)]
    for (backend, net), rs in sorted(by_variant.items()):
        ok = [r for r in rs if not r["void"]]
        cells = [f"{backend} / {net}", f"{len(ok)}/{len(rs)}"]
        cells += [fmt_ns(median(stage(r, "send_to_user", p) for r in ok)) for p in PERCENTILES]
        cells += [fmt_ns(median(stage(r, "kernel_to_user", p) for r in ok)) for p in ("p50", "p99")]
        msgs = median(rate(r) for r in ok)
        lost = median(loss(r) for r in ok)
        cells += [f"{msgs:,.0f}" if msgs else "", f"{lost:.2%}" if lost else ""]
        lines.append("| " + " | ".join(cells) + " |")
    return lines


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("results")
    parser.add_argument("--env")
    parser.add_argument("-o", "--out", required=True)
    args = parser.parse_args()

    results = json.loads(pathlib.Path(args.results).read_text())
    runs = results["runs"]
    out = ["# Network benchmarks", "",
           f"_Generated by `tools/netbench`. Started {results['started']}, "
           f"{results['reps']} repetitions per variant, medians of the valid ones._", ""]
    if args.env and pathlib.Path(args.env).exists():
        env = json.loads(pathlib.Path(args.env).read_text())
        out += ["## Fingerprint", ""]
        out += [f"- `{k}`: {v}" for k, v in env.items() if not isinstance(v, (dict, list))]
        out.append("")

    plots = pathlib.Path(args.out).parent / "plots"
    if plots.is_dir():
        out += ["## Plots", ""]
        out += [f"![{png.stem}](plots/{png.name})" for png in sorted(plots.glob("*.png"))]
        out.append("")

    workloads = defaultdict(list)
    for r in runs:
        workloads[(r["suite"], r["workload"])].append(r)
    suite = None
    for (s, name), rs in workloads.items():
        if s != suite:
            suite = s
            out += [f"## {s}", ""]
        args_text = " ".join(rs[0]["peer_args"])
        out += [f"### {name}", "", f"`{args_text}`", "", *table(rs), ""]

    void = [r for r in runs if r["void"]]
    if void:
        out += ["## Void runs", ""]
        out += [f"- {r['workload']} {r['backend']} / {r['net']} rep {r['rep']}: {r['void']}"
                for r in void]
        out.append("")
    pathlib.Path(args.out).write_text("\n".join(out))


if __name__ == "__main__":
    main()
